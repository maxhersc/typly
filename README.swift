# Typly

Typly is a macOS AI typing assistant built with Swift.

It runs as a lightweight desktop overlay and can:
- monitor global text input
- classify context
- transform text with AI
- execute actions automatically
- display a transparent floating interface

## Features

- Global keyboard/input monitoring
- Context-aware text transformation
- Transparent overlay UI
- Native macOS app
- Swift + AppKit architecture
- Accessibility API integration

## Tech Stack

- Swift
- AppKit
- Accessibility APIs
- Swift Package Manager

## Requirements

- macOS
- Accessibility permissions enabled

